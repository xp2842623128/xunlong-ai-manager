export const PRESETS = [...BASE_PRESETS, ...GENERATED_PRESETS];

export function presetsFor(app) {
  return PRESETS.filter((p) => p.app === app);
}

export function findPreset(id) {
  return PRESETS.find((p) => p.id === id) || null;
}

export function presetToProvider(preset, apiKey = '') {
  return {
    name: preset.name,
    app: preset.app,
    protocol: preset.protocol,
    baseUrl: preset.baseUrl,
    apiKey,
    model: preset.model || '',
    models: preset.models || [],
    website: preset.website || '',
    keyUrl: preset.keyUrl || '',
    note: preset.note || '',
    presetId: preset.id,
  };
}
